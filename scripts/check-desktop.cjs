    await toolbox.locator('#planText').fill('完成今天的阅读');
    await toolbox.locator('#addPlan').click();
    assert.equal(await toolbox.locator('#taskList .task').count(),1);
    await toolbox.locator('#taskList input').check();
    await toolbox.locator('[data-view="todo"]').click();
    await toolbox.locator('#todoText').fill('准备下周的资料');
    await toolbox.locator('#addTodo').click();
