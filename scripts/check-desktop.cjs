    const request=await app.evaluate(()=>global.fixture.requests.find(r=>!r.instructions?.includes('professional translator')));
    assert.deepEqual(request.input[0].content.map(x=>x.type),['input_text','input_image','input_file']);
    assert.equal(request.stream,true);
