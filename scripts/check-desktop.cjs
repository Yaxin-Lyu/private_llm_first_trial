    assert.ok(sourceBox.width>200&&resultBox.x>sourceBox.x+sourceBox.width);
    await page.screenshot({path:path.join(out,'translation-small.png')});
    await testWindow.evaluate(w=>w.setSize(1220,820));
    await toolbox.locator('#translation-swap').click();
    assert.equal(await toolbox.locator('#translation-source-language').inputValue(),'zh-CN');
    assert.equal(await toolbox.locator('#translation-target-language').inputValue(),'en');
